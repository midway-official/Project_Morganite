/** 处理器顶层导出的只读性能观测接口。
  *
  * 各字段表示当前拍的窄事件或状态，不在硬件中设置累计计数器。
  * dispatch/issue/retire/branch 载荷提供 PC、指令和 ROB 标签；valid 为 0
  * 时载荷无定义。仿真侧可用 ROB 标签连接队列等待、写回及退休阶段。
  * Verilator 每拍采样后在软件侧使用 64 位计数器累加，避免该接口
  * 进入控制关键路径，也减少 FPGA 资源和时序影响。
  */
class PerfEvents(implicit p: AuroraConfig) extends Bundle {
  val dcacheFillOccupancy = UInt(p.dcacheFillContextCountBits.W)
  val dcacheFillFull = Bool()
  val bus = new BusPerfEvents
  private val widthCountBits = p.issueCountBits

  val active = Bool()
  val cycle  = UInt(32.W)

  val commitCount          = UInt(widthCountBits.W)
  val commitRegwriteCount  = UInt(widthCountBits.W)
  val commitStoreCount     = UInt(widthCountBits.W)
  val commitSystemCount    = UInt(widthCountBits.W)
  val commitBranchCount    = UInt(widthCountBits.W)

  val branchValid      = Bool()
  val branchMispredict = Bool()

  val icacheAccess     = Bool()
  val icacheMiss       = Bool()
  val icacheRefillBeat = Bool()
  val fetchCount       = UInt(widthCountBits.W)
  val l1Lookup         = Bool()
  val l1Hit            = Bool()
  val l1Taken          = Bool()
  val predictionRedirect = Bool()
  val predictionRedirectPc = UInt(32.W)

  val isuInputValid    = Bool()
  val isuDispatchCount = UInt(widthCountBits.W)

  val aluIqOccupancy = Vec(p.numAlu, UInt(p.aluIqCountBits.W))
  val bruIqOccupancy = UInt(p.bruIqCountBits.W)
  val lsuIqOccupancy = UInt(p.lsuIqCountBits.W)
  val aluIssue       = Vec(p.numAlu, Bool())
  val aluIssueEvent  = Vec(p.numAlu, new PerfIssueEvent)
  val aluWritebackEvent = Vec(p.numAlu, new PerfWritebackEvent)
  val bruIssue       = Bool()
  val bruIssueEvent  = new PerfIssueEvent
  val lsuIssue       = Bool()
  val lsuIssueEvent  = new PerfIssueEvent
  val divIssueEvent  = Vec(p.numDiv, new PerfIssueEvent)
  val divWritebackEvent = Vec(p.numDiv, new PerfWritebackEvent)

  val robOccupancy = UInt(p.robCountBits.W)
  val flush          = Bool()
  val robHeadIdx      = UInt(p.robIdxBits.W)
  val robHeadPc       = UInt(p.xLen.W)
  val robHeadDone     = Bool()
  val robHeadIsLoad   = Bool()
  val robHeadIsStore  = Bool()
  val robHeadIsBranch = Bool()
  val dispatchEvent = Vec(p.coreWidth, new PerfDispatchEvent)
  val commitPc        = Vec(p.coreWidth, UInt(p.xLen.W))
  val retireEvent     = Vec(p.coreWidth, new PerfRetireEvent)
  val branchExecuteEvent = new PerfBranchEvent
  val bruExecuteValid = Bool()
  val bruExecutePc = UInt(p.xLen.W)
  val bruExecuteTarget = UInt(p.xLen.W)
  val bruExecuteSrc1 = UInt(p.xLen.W)
  val bruExecuteRobIdx = UInt(p.robIdxBits.W)
  val bruExecuteOp = UInt(UopConst.brOpBits.W)
  val bruExecuteMispredict = Bool()

  val loadIssue     = Bool()
  val storeIssue    = Bool()
  val loadComplete = Bool()
  val dcacheHit = Bool()
  val dcacheHitRobIdx = UInt(p.robIdxBits.W)
  val dcacheHitUnderMiss = Bool()
  val dcacheMshrBusy = Bool()
  val dcacheMshrOccupancy = UInt(p.dcacheMshrCountBits.W)
  val lsuBusy       = Bool()
  val lsuInputStall = Bool()
  val loadReqWait   = Bool()
  val loadRespWait  = Bool()
  val storeReqWait  = Bool()
  val lqOccupancy   = UInt(p.lqCountBits.W)
  val sqOccupancy   = UInt(p.sqCountBits.W)

  val loadAddressAccepted = Bool()
  val loadAddressPrd = UInt(p.physRegBits.W)
  val storeBufferLookup = Bool()
  val storeBufferLookupPrd = UInt(p.physRegBits.W)
  val loadBusRequestAccepted = Bool()
  val loadBusRequestPrd = UInt(p.physRegBits.W)
  val loadBusResponse = Bool()
  val loadBusResponsePrd = UInt(p.physRegBits.W)
  val loadScheduledWake = Bool()
  val loadScheduledWakePrd = UInt(p.physRegBits.W)
  val loadUseIssue = Vec(p.numAlu, Bool())
  val loadUseIssuePc = Vec(p.numAlu, UInt(p.xLen.W))
  val loadUseIssuePrd = Vec(p.numAlu, UInt(p.physRegBits.W))
  val loadUseExecute = Vec(p.numAlu, Bool())
  val loadUseExecutePc = Vec(p.numAlu, UInt(p.xLen.W))
  val loadUseExecutePrd = Vec(p.numAlu, UInt(p.physRegBits.W))
  val loadUseConsumerPrd = Vec(p.numAlu, UInt(p.physRegBits.W))
  val aluLocalWake = Vec(p.numAlu, Bool())
  val aluLocalWakePrd = Vec(p.numAlu, UInt(p.physRegBits.W))
  val localFollowerAdvance = Vec(p.numAlu, Bool())

  val lsuReadyLoadPresent = Bool()
  val lsuAguStageValid = Bool()
  val lsuStoreBufferStageValid = Bool()
  val lsuResultStageValid = Bool()
  val lsuBusOwnerValid = Bool()
  val lsuBusRequestBlocked = Bool()
  val lsuOlderStoreBlocked = Bool()
  val dcacheStoreUpdateEnq = Bool()
  val dcacheStoreUpdateMerge = Bool()
  val dcacheStoreUpdateComplete = Bool()
  val dcacheStoreFastHit = Bool()
  val dcacheStorePartialHit = Bool()
  val dcacheStoreMiss = Bool()
  val dcacheStoreFifoFull = Bool()
  val dcacheStoreFifoOccupancy = UInt(p.dcacheStoreUpdateQueueCountBits.W)
  val dcacheLoadRefill = Bool()
  val dcacheStoreRefill = Bool()
  val dcacheVictimCapture = Bool()
  val dcacheWbFullWait = Bool()
  val dcacheWbOccupancy = UInt(p.dcacheWritebackQueueCountBits.W)
  val dcacheSameLineRawWait = Bool()
  val dcacheSameLineRefillResponse = Bool()
  val dcacheStoreRefillBlocked = Bool()
  val dcacheStoreRefillDifferentWay = Bool()
  val dcacheStoreRefillParallel = Bool()
  val dcacheSameSetFillParallel = Bool()
  val dcacheWaiterDetached = Bool()
  val dcacheMissQueuedBehindEngine = Bool()
  val dcacheMissQueuedSameLine = Bool()
  val dcacheStoreHeadSameSetWait = Bool()
  val dcacheStoreHeadSameLineWait = Bool()
  val lsuIssuePc = UInt(p.xLen.W)
  val lsuIssueRobIdx = UInt(p.robIdxBits.W)
  val lsuCdbValid = Bool()
  val lsuCdbRobIdx = UInt(p.robIdxBits.W)
  val lsuCdbPrd = UInt(p.physRegBits.W)
  val lsuCdbIsCacheableLoad = Bool()
}
